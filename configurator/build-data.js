// Generates wizard-data.js for the web configurator from the template's own metadata
// (template.json, ide.host.json, dotnetcli.host.json) and the wizard's WizardSteps.json,
// so the browser wizard, the Visual Studio wizard and "dotnet new" always offer the same options.
//
//   node configurator/build-data.js
//
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const read = f => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));
const template = read('templates/RazorSolution/.template.config/template.json');
const ide = read('templates/RazorSolution/.template.config/ide.host.json');
const cli = read('templates/RazorSolution/.template.config/dotnetcli.host.json');
const wizard = read('wizard/src/RazorSolution.Wizard.Core/WizardSteps.json');

const ideInfo = Object.fromEntries(ide.symbolInfo.map(s => [s.id, s]));
const fields = {};
for (const [id, s] of Object.entries(template.symbols)) {
  if (s.type !== 'parameter' || id === 'skipRestore') continue;
  const kind = s.datatype === 'bool' ? 'bool' : s.datatype === 'choice' ? 'choice' : 'text';
  fields[id] = {
    id,
    kind,
    label: ideInfo[id]?.name?.text || s.displayName || id,
    description: ideInfo[id]?.description?.text || s.description || '',
    default: s.defaultValue ?? (kind === 'bool' ? 'false' : ''),
    choices: (s.choices || []).map(c => ({ value: c.choice, display: c.displayName || c.description || c.choice })),
    cli: id === 'Framework' ? '--framework' : '--' + (cli.symbolInfo[id]?.longName || id),
  };
}

const data = {
  generated: 'Generated by configurator/build-data.js - do not edit.',
  templateName: template.name,
  shortName: template.shortName,
  packageId: 'DotNetAppDev.RazorSolution.Templates',
  defaultName: template.defaultName || 'MyCompany.Portal',
  fields,
  steps: wizard.steps,
  fieldRules: wizard.fieldRules,
  passwordFields: wizard.passwordFields,
  tiles: wizard.tiles,
};

const out = path.join(__dirname, 'wizard-data.js');
fs.writeFileSync(out, `// ${data.generated}\nwindow.WIZARD_DATA = ${JSON.stringify(data, null, 1)};\n`);
console.log('wrote', path.relative(root, out), `(${Object.keys(fields).length} options, ${wizard.steps.length} steps)`);
